import { readFile, writeFile } from 'node:fs/promises'
import { splitListEntries } from '../src/core/security/site-list.ts'

const sourceUrl = new URL('../src/core/security/site-list-entries.json', import.meta.url)
const registryUrl = new URL('../../rpc-registry/src/site-list.ts', import.meta.url)
const extensionPathsUrl = new URL('../src/core/security/site-list-paths.ts', import.meta.url)

function stringArray(values: readonly string[]): string {
  if (values.length === 0) return '[]'
  return `[\n${values.map(value => `  ${JSON.stringify(value)}`).join(',\n')}\n]`
}

const source: unknown = JSON.parse(await readFile(sourceUrl, 'utf8'))
if (!Array.isArray(source) || source.some(entry => typeof entry !== 'string')) {
  throw new Error('Site list source must be a string array')
}

const split = splitListEntries(source)
for (const value of [...split.hostnames, ...split.ips]) {
  if (value.includes('/')) throw new Error('Refusing to publish a path as a host')
}
if (split.hostnames.length > 0 || split.ips.length > 0) {
  throw new Error('Refusing to publish site-list hosts without a role signature')
}

const registry = `// Generated by packages/extension/scripts/split-site-list-entries.ts.
// Hostnames and IP addresses only. URL prefixes are not published.
// Remote entries ship inside signed documents. This build has none.

export const SITE_LIST = {
  documents: []
} as const
`

const extensionPaths = `// Generated by packages/extension/scripts/split-site-list-entries.ts.
// Local URL prefixes. This module is not served by the registry.

export const SITE_LIST_PATHS: readonly string[] = ${stringArray(split.paths)}
`

await writeFile(registryUrl, registry)
await writeFile(extensionPathsUrl, extensionPaths)
